import '../domain/app_models.dart';
import 'adif_codec.dart';
import 'qso_repository.dart';

class GeneratedExport {
  const GeneratedExport({
    required this.content,
    required this.qsoIds,
    required this.confirmedQsoVersions,
  });

  final String content;
  final List<String> qsoIds;
  final Map<String, DateTime> confirmedQsoVersions;
}

class ExportService {
  ExportService(this._qsoRepository);

  final QsoRepository _qsoRepository;

  Future<GeneratedExport> exportAdif(ExportFilter filter) async {
    final qsos = await _qsoRepository.listQsos(_queryFromFilter(filter));
    final buffer = StringBuffer()
      ..writeln('Generated by QSO Scribe')
      ..writeln('<PROGRAMID:10>QSO Scribe')
      ..writeln('<EOH>');

    for (final qso in qsos) {
      buffer.writeln(toAdifRecord(qso));
    }
    return _generatedExport(buffer.toString(), qsos);
  }

  Future<GeneratedExport> exportCsv(ExportFilter filter) async {
    final qsos = await _qsoRepository.listQsos(_queryFromFilter(filter));
    final buffer = StringBuffer()
      ..writeln(
        [
          'Callsign',
          'DateTime',
          'Band',
          'Frequency',
          'Mode',
          'SentRST',
          'ReceivedRST',
          'Name',
          'QTH',
          'Notes',
          'Rig',
          'Antenna',
          'Status',
        ].join(','),
      );

    for (final qso in qsos) {
      buffer.writeln(
        [
          qso.callsign.value,
          qso.dateTime.value?.toUtc().toIso8601String() ?? '',
          qso.band.value,
          qso.frequency.value,
          qso.mode.value,
          qso.sentRst.value,
          qso.receivedRst.value,
          qso.name?.value ?? '',
          qso.qth?.value ?? '',
          qso.notes?.value ?? '',
          qso.rig?.value ?? '',
          qso.antenna?.value ?? '',
          qso.status.name,
        ].map(_csvCell).join(','),
      );
    }

    return _generatedExport(buffer.toString(), qsos);
  }

  Future<GeneratedExport> exportRawTranscript(ExportFilter filter) async {
    final qsos = await _qsoRepository.listQsos(_queryFromFilter(filter));
    final buffer = StringBuffer();
    for (final qso in qsos) {
      buffer
        ..writeln('## ${qso.callsign.value}')
        ..writeln('Status: ${qso.status.name}')
        ..writeln('Date: ${qso.dateTime.value?.toIso8601String() ?? ''}')
        ..writeln(qso.rawTranscript ?? '')
        ..writeln();
    }
    return _generatedExport(buffer.toString(), qsos);
  }

  GeneratedExport _generatedExport(String content, List<QsoDraft> qsos) {
    final qsoIds = <String>[];
    final confirmedQsoVersions = <String, DateTime>{};
    for (final qso in qsos) {
      final id = qso.id;
      if (id == null) {
        throw StateError('persisted_qso_id_missing');
      }
      qsoIds.add(id);
      if (qso.status == LogStatus.confirmed) {
        final updatedAt = qso.updatedAt;
        if (updatedAt == null) {
          throw StateError('persisted_qso_version_missing');
        }
        confirmedQsoVersions[id] = updatedAt;
      }
    }
    return GeneratedExport(
      content: content,
      qsoIds: qsoIds,
      confirmedQsoVersions: confirmedQsoVersions,
    );
  }

  QsoQuery _queryFromFilter(ExportFilter filter) {
    return QsoQuery(
      status: filter.status,
      from: filter.from,
      to: filter.to,
      band: filter.band,
      mode: filter.mode,
    );
  }

  String _csvCell(String value) {
    final escaped = value.replaceAll('"', '""');
    return '"$escaped"';
  }
}
